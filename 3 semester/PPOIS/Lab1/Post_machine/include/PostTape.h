/**
 * @file PostTape.h
 * @author Student (Лабораторная работа №1, ППОИС)
 * @brief Заголовочный файл класса PostTape (Лента и каретка машины Поста).
 * @details Описывает бесконечную в обе стороны двоичную ленту машины Поста и каретку
 * (головку чтения/записи). Поддерживает динамическое выделение памяти, перемещение
 * каретки операторами инкремента и декремента (++ и --), установку/стирание меток,
 * индексацию секций и потоковый ввод/вывод.
 */

#ifndef POST_TAPE_H
#define POST_TAPE_H

#include <cstddef>
#include <iostream>
#include <stdexcept>
#include <string>

/**
 * @class PostTape
 * @brief Класс, реализующий ленту и каретку машины Поста.
 * @details Лента состоит из целочисленных позиций (отрицательных, нулевой и положительных),
 * в каждой секции может находиться либо `0` (пусто), либо `1` (метка).
 * Хранение реализовано через динамический массив (`new bool[]` / `delete[]`), который
 * автоматически расширяется при обращении за пределы текущего диапазона.
 */
class PostTape {
public:
    /**
     * @brief Конструктор по умолчанию. Создаёт пустую ленту с кареткой в позиции 0.
     */
    PostTape();

    /**
     * @brief Конструктор ленты из строки состояния (например, `"01101"` или `"01[1]01"`).
     * @details Символы `'0'` и `'.'` означают пустую клетку, `'1'` — метку.
     * Если один из символов заключён в квадратные скобки `[1]` или `[0]`, каретка
     * устанавливается на эту клетку.
     * @param stateStr Строковое представление ленты.
     * @param initialCarriage Начальная позиция каретки (если в строке не указаны скобки `[...]`).
     * @throw std::invalid_argument При наличии недопустимых символов в строке.
     */
    explicit PostTape(const std::string& stateStr, int initialCarriage = 0);

    /**
     * @brief Конструктор ленты из C-строки (`const char*`).
     * @param stateStr Указатель на C-строку состояния ленты.
     * @param initialCarriage Начальная позиция каретки.
     * @throw std::invalid_argument Если `stateStr == nullptr` или содержит недопустимые символы.
     */
    explicit PostTape(const char* stateStr, int initialCarriage = 0);

    /**
     * @brief Конструктор копирования (глубокое копирование динамического массива ленты).
     * @param other Копируемая лента.
     */
    PostTape(const PostTape& other);

    /**
     * @brief Деструктор класса. Освобождает динамически выделенную память (`delete[]`).
     */
    ~PostTape();

    /**
     * @brief Оператор присваивания копированием.
     * @param other Присваиваемый объект ленты.
     * @return Ссылка на текущий объект (`*this`).
     */
    PostTape& operator=(const PostTape& other);

    /**
     * @brief Возвращает текущую целочисленную координату каретки (inline-метод).
     * @return Индекс секции, над которой находится каретка.
     */
    int carriagePosition() const {
        return this->carriage_;
    }

    /**
     * @brief Устанавливает позицию каретки на ленте.
     * @param position Новая координата каретки.
     */
    void setCarriagePosition(int position);

    /**
     * @brief Проверяет, стоит ли метка (`1`) в секции под кареткой.
     * @return `true`, если под кареткой стоит метка, иначе `false`.
     */
    bool isMarked() const;

    /**
     * @brief Ставит метку (`1`) в текущей секции под кареткой (команда `V`).
     * @throw std::logic_error Если в текущей секции уже стоит метка (по строгой семантике Поста),
     * если не включён мягкий режим, либо через `setCell` можно менять свободно.
     */
    void mark();

    /**
     * @brief Стирает метку (`0`) в текущей секции под кареткой (команда `X`).
     */
    void erase();

    /**
     * @brief Задаёт или изменяет значение в произвольной секции ленты по индексу.
     * @param index Индекс секции (может быть отрицательным, нулём или положительным).
     * @param value Новое значение (`true` — метка `1`, `false` — пусто `0`).
     */
    void setCell(int index, bool value);

    /**
     * @brief Возвращает значение произвольной секции ленты по индексу.
     * @param index Индекс секции.
     * @return `true`, если в секции `index` стоит метка, иначе `false`.
     */
    bool getCell(int index) const;

    /**
     * @brief Оператор индексации `[]` для чтения/изменения значения секции ленты по индексу.
     * @param index Индекс секции ленты.
     * @return Ссылка на булеву ячейку внутри динамического массива (при необходимости массив расширяется).
     */
    bool& operator[](int index);

    /**
     * @brief Константный оператор индексации `[]` для чтения значения секции ленты.
     * @param index Индекс секции ленты.
     * @return `true`, если в секции `index` стоит метка, иначе `false`.
     */
    bool operator[](int index) const;

    /**
     * @brief Сдвигает каретку на одну секцию вправо.
     */
    void moveRight();

    /**
     * @brief Сдвигает каретку на одну секцию влево.
     */
    void moveLeft();

    /**
     * @brief Префиксный оператор инкремента (`++tape`) — сдвигает каретку вправо.
     * @return Ссылка на текущий объект (`*this`).
     */
    PostTape& operator++();

    /**
     * @brief Постфиксный оператор инкремента (`tape++`) — сдвигает каретку вправо.
     * @return Копия состояния ленты до сдвига каретки.
     */
    PostTape operator++(int);

    /**
     * @brief Префиксный оператор декремента (`--tape`) — сдвигает каретку влево.
     * @return Ссылка на текущий объект (`*this`).
     */
    PostTape& operator--();

    /**
     * @brief Постфиксный оператор декремента (`tape--`) — сдвигает каретку влево.
     * @return Копия состояния ленты до сдвига каретки.
     */
    PostTape operator--(int);

    /**
     * @brief Очищает ленту (стирает все метки) и возвращает каретку в позицию 0.
     */
    void clear();

    /**
     * @brief Подсчитывает общее количество меток (`1`) на всей ленте.
     * @return Число установленных меток (`std::size_t`).
     */
    std::size_t countMarks() const;

    /**
     * @brief Загружает состояние ленты из строки.
     * @param stateStr Строка из символов `'0'`, `'1'`, `'.'` и опциональных скобок `[...]`.
     * @param initialCarriage Позиция каретки по умолчанию.
     * @throw std::invalid_argument При некорректном формате строки.
     */
    void loadFromString(const std::string& stateStr, int initialCarriage = 0);

    /**
     * @brief Загружает состояние ленты из входного потока.
     * @param is Входной поток (`std::istream&`).
     * @return Ссылка на входной поток.
     */
    std::istream& loadFromStream(std::istream& is);

    /**
     * @brief Возвращает наглядное строковое представление ленты с выделением позиции каретки `[0]`/`[1]`.
     * @details Использует `mutable`-поля для кэширования результата при константных обращениях.
     * @return Константная ссылка на строковое представление ленты.
     */
    const std::string& toString() const;

    /**
     * @brief Возвращает компактную строку только из символов `'0'` и `'1'` без скобок каретки.
     * @return Строка значений видимого диапазона ленты.
     */
    std::string toPlainString() const;

    /**
     * @brief Оператор сравнения двух лент на равенство (`==`).
     * @details Две ленты считаются равными, если позиции их кареток совпадают и множества
     * всех отмеченных секций (`1`) идентичны.
     * @param other Вторая лента для сравнения.
     * @return `true`, если ленты и позиции кареток равны, иначе `false`.
     */
    bool operator==(const PostTape& other) const;

    /**
     * @brief Оператор сравнения двух лент на неравенство (`!=`).
     * @param other Вторая лента для сравнения.
     * @return `true`, если ленты различаются, иначе `false`.
     */
    bool operator!=(const PostTape& other) const;

    /**
     * @brief Потоковый оператор вывода ленты (`<<`).
     * @param os Выходной поток.
     * @param tape Выводимая лента.
     * @return Ссылка на выходной поток.
     */
    friend std::ostream& operator<<(std::ostream& os, const PostTape& tape);

    /**
     * @brief Потоковый оператор ввода ленты (`>>`).
     * @param is Входной поток.
     * @param tape Заполняемая лента.
     * @return Ссылка на входной поток.
     */
    friend std::istream& operator>>(std::istream& is, PostTape& tape);

private:
    bool* cells_;                       ///< Динамический массив ячеек ленты.
    int minIndex_;                      ///< Минимальный индекс, соответствующий `cells_[0]`.
    std::size_t capacity_;              ///< Общее количество выделенных ячеек в `cells_`.
    int carriage_;                      ///< Текущая координата каретки.

    mutable std::string cachedRepr_;    ///< Кэшированное строковое представление (`mutable`).
    mutable bool isCacheValid_;         ///< Флаг актуальности кэша (`mutable`).

    /**
     * @brief Гарантирует, что индекс `index` входит в выделенный диапазон `[minIndex_, minIndex_ + capacity_)`.
     * @param index Требуемый индекс секции.
     */
    void ensureRange(int index);

    /**
     * @brief Сбрасывает кэш строкового представления.
     */
    void invalidateCache() const;
};

#endif // POST_TAPE_H
