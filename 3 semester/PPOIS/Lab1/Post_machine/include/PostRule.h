/**
 * @file PostRule.h
 * @author Student (Лабораторная работа №1, ППОИС)
 * @brief Заголовочный файл класса PostRule (Правило / команда машины Поста).
 * @details Описывает отдельную команду машины Поста: её уникальный номер, тип операции
 * (поставить метку, стереть метку, сдвиг вправо, сдвиг влево, условный переход, останов)
 * и номера следующих правил перехода.
 */

#ifndef POST_RULE_H
#define POST_RULE_H

#include <iostream>
#include <stdexcept>
#include <string>

/**
 * @class PostRule
 * @brief Класс, представляющий одно правило (инструкцию) программы машины Поста.
 * @details Поддерживает следующие команды машины Поста:
 * - `'V'` (или `'1'`) — поставить метку и перейти к правилу `next1`;
 * - `'X'` (или `'0'`) — стереть метку и перейти к правилу `next1`;
 * - `'>'` (или `'R'`) — сдвинуть каретку вправо и перейти к правилу `next1`;
 * - `'<'` (или `'L'`) — сдвинуть каретку влево и перейти к правилу `next1`;
 * - `'?'` — условный переход: если под кареткой `0` (пусто), перейти к `next1`; если `1` (метка) — к `next2`;
 * - `'!'` (или `'.'`) — команда останова (завершение работы программы).
 */
class PostRule {
public:
    /**
     * @enum Action
     * @brief Перечисление допустимых операций машины Поста.
     */
    enum class Action {
        Mark = 'V',      ///< Поставить метку ('V')
        Erase = 'X',     ///< Стереть метку ('X')
        MoveRight = '>', ///< Сдвинуть каретку вправо ('>')
        MoveLeft = '<',  ///< Сдвинуть каретку влево ('<')
        Branch = '?',    ///< Условный переход ('?'): если 0 -> next1, если 1 -> next2
        Halt = '!'       ///< Останов машины ('!')
    };

    /**
     * @brief Конструктор по умолчанию. Создаёт правило останова `1: !`.
     */
    PostRule();

    /**
     * @brief Конструктор создания правила машины Поста.
     * @param id Номер правила (положительное целое число).
     * @param action Тип действия (`Action`).
     * @param next1 Номер следующего правила (для `'?'` — переход при пустой секции `0`).
     * @param next2 Номер второго перехода (используется только для `'?'` при наличии метки `1`).
     * @throw std::invalid_argument Если `id <= 0` или номера переходов некорректны.
     */
    PostRule(int id, Action action, int next1 = -1, int next2 = -1);

    /**
     * @brief Конструктор создания правила с символьным кодом операции (`char`).
     * @param id Номер правила (`> 0`).
     * @param actionChar Символ операции (`'V'`, `'X'`, `'>'`, `'<'`, `'?'`, `'!'`).
     * @param next1 Номер первого перехода.
     * @param next2 Номер второго перехода (для `'?'`).
     * @throw std::invalid_argument При неизвестном символе операции или некорректных номерах.
     */
    PostRule(int id, char actionChar, int next1 = -1, int next2 = -1);

    /**
     * @brief Конструктор копирования.
     * @param other Копируемое правило.
     */
    PostRule(const PostRule& other);

    /**
     * @brief Деструктор класса.
     */
    ~PostRule();

    /**
     * @brief Оператор присваивания копированием.
     * @param other Присваиваемое правило.
     * @return Ссылка на текущий объект (`*this`).
     */
    PostRule& operator=(const PostRule& other);

    /**
     * @brief Возвращает номер правила (inline-метод).
     * @return Целочисленный идентификатор правила.
     */
    int id() const {
        return this->id_;
    }

    /**
     * @brief Возвращает действие правила (inline-метод).
     * @return Значение перечисления `Action`.
     */
    Action action() const {
        return this->action_;
    }

    /**
     * @brief Возвращает канонический символ действия (`'V'`, `'X'`, `'>'`, `'<'`, `'?'`, `'!'`).
     * @return Символ действия.
     */
    char actionChar() const;

    /**
     * @brief Возвращает номер основного перехода `next1` (inline-метод).
     * @return Номер следующего правила (или `-1` для команды останова `'!'`).
     */
    int next1() const {
        return this->next1_;
    }

    /**
     * @brief Возвращает номер альтернативного перехода `next2` для команды `'?'` (inline-метод).
     * @return Номер второго правила перехода (при наличии метки `1`).
     */
    int next2() const {
        return this->next2_;
    }

    /**
     * @brief Форматирует правило в строку вида `"1: > 2"` или `"2: ? 3, 4"` или `"5: !"`.
     * @return Строковое представление правила.
     */
    std::string toString() const;

    /**
     * @brief Статический метод разбора правила из строки.
     * @details Поддерживает форматы вида `"1: V 2"`, `"2 ? 3, 4"`, `"5: !"`, `"1. > 2"`.
     * @param line Строка с описанием правила.
     * @return Сформированный объект `PostRule`.
     * @throw std::invalid_argument При синтаксической ошибке в строке.
     */
    static PostRule fromString(const std::string& line);

    /**
     * @brief Статический метод преобразования символа в `Action`.
     * @param ch Символ команды (`'V'`/`'1'`, `'X'`/`'0'`, `'>'`/`'R'`, `'<'`/`'L'`, `'?'`, `'!'`/`'.'`).
     * @return Соответствующее значение `Action`.
     * @throw std::invalid_argument Если символ не соответствует ни одной команде.
     */
    static Action charToAction(char ch);

    /**
     * @brief Оператор проверки на равенство (`==`).
     * @param other Другое правило.
     * @return `true`, если все поля правил совпадают.
     */
    bool operator==(const PostRule& other) const;

    /**
     * @brief Оператор проверки на неравенство (`!=`).
     * @param other Другое правило.
     * @return `true`, если правила различаются.
     */
    bool operator!=(const PostRule& other) const;

    /**
     * @brief Потоковый оператор вывода правила (`<<`).
     * @param os Выходной поток.
     * @param rule Выводимое правило.
     * @return Ссылка на выходной поток.
     */
    friend std::ostream& operator<<(std::ostream& os, const PostRule& rule);

    /**
     * @brief Потоковый оператор ввода правила (`>>`).
     * @param is Входной поток.
     * @param rule Считываемое правило.
     * @return Ссылка на входной поток.
     */
    friend std::istream& operator>>(std::istream& is, PostRule& rule);

private:
    int id_;         ///< Номер правила (> 0).
    Action action_;  ///< Выполняемая операция.
    int next1_;      ///< Основной переход (или переход по 0 для '?').
    int next2_;      ///< Второй переход по 1 (только для '?').

    /**
     * @brief Проверяет корректность параметров правила и выбрасывает исключение при ошибке.
     */
    void validate() const;
};

#endif // POST_RULE_H
